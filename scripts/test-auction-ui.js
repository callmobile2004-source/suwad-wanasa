const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.resolve(__dirname,"..");
const js=fs.readFileSync(path.join(root,"auction-ui.js"),"utf8");
const css=fs.readFileSync(path.join(root,"auction-ui.css"),"utf8");
const expected=["football-players","wrestlers","rare-animals","cars","watches","video-games","real-estate","aircraft-ships","antiques","rare-cards","fictional-gear","mystery-lots"];
const layouts=["stadium","arena","wild","garage","atelier","arcade","estate","fleet","museum","cards","fantasy","mystery"];
const ids=[...js.matchAll(/id:"([a-z-]+)",name:/g)].map(m=>m[1]);
assert.deepEqual(ids,expected,"The auction category registry must contain exactly the twelve approved categories in order");
for(const id of expected) assert.ok(js.includes("id:"+JSON.stringify(id)), "Missing category "+id);
for(const layout of layouts){
  assert.ok(js.includes(layout+":"), "Missing dedicated layout template "+layout);
  assert.ok(css.includes(".auction-layout-"+layout), "Missing dedicated layout styling "+layout);
}
assert.equal(new Set(layouts).size,layouts.length,"Each category must use a distinct layout");
assert.ok(js.includes("المزاد افتراضي وتثقيفي فقط"),"Rare animals must remain educational and virtual only");
assert.ok(js.includes("بلا أسلحة حقيقية"),"Fictional equipment must not imply real weapon trading");
assert.ok(js.includes("data-auction-back"),"Category screens must provide a return path to the auction hub");
assert.ok(js.includes("data-auction-category"),"The hub must provide category navigation");
assert.ok(js.includes("auction-engine"),"The category screens must use the authenticated auction Edge Function");
assert.ok(js.includes("m.signed_url"),"Auction media must use short-lived server-signed URLs");
assert.ok(!js.includes("getPublicUrl"),"Auction media must not use public bucket URLs");
assert.ok(js.includes("auction_commentator"),"The category screens must expose Oras auction commentary");
assert.ok(js.includes("SuwadVoice.speak"),"Oras commentary should use existing voice support when available");
assert.ok(js.includes("data-auction-media")&&js.includes("auction-gallery-thumbs"),"Each item gallery must support photo/GIF navigation");
assert.ok(js.includes("data-auction-create")&&js.includes("data-auction-join"),"The category screens must support room creation and joining");
assert.ok(js.includes("postgres_changes"),"Auction rooms must refresh through Realtime subscriptions");
assert.ok(js.includes("data-auction-bid"),"The category screens must expose server-validated bidding");
assert.ok(js.includes("loadAuctionCatalog"),"Each category must load its actual active text catalog");
assert.ok(js.includes('from("auction_items")')&&js.includes('eq("is_active",true)'),"Catalog reads must include only active items");
assert.ok(js.includes("auction-catalog-list")&&js.includes("estimated_value")&&js.includes("opening_price"),"Catalog cards must display descriptions and virtual prices");
assert.ok(js.includes("الصور اختيارية")||js.includes("الصور غير مطلوبة"),"No-image play must be explained in the category screen");
assert.ok(js.includes('value="3" selected'),"The default room must start with three available catalog lots");
console.log("PASS: 12 auction categories, 12 distinct layouts, category-specific facts, safe category constraints and navigation.");
