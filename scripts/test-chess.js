"use strict";
const assert=require("node:assert/strict");
const {Chess}=require("../chess.js");
const game=new Chess();
assert.equal(game.moves().length,20,"starting position must expose 20 legal moves");
assert.equal(game.move({from:"e2",to:"e4"}).san,"e4","pawn opening must work");
assert.equal(game.turn(),"b","turn must change after a legal move");
assert.equal(game.move({from:"e7",to:"e4"}),null,"illegal move must be rejected");
const castle=new Chess("r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1");
const castleMoves=castle.moves({square:"e1",verbose:true});
assert(castleMoves.some(m=>m.to==="g1"&&m.flags.includes("k")),"king-side castling must be legal");
assert(castleMoves.some(m=>m.to==="c1"&&m.flags.includes("q")),"queen-side castling must be legal");
const promotion=new Chess("7k/P7/8/8/8/8/8/7K w - - 0 1");
assert.equal(promotion.moves({square:"a7",verbose:true}).filter(m=>m.to==="a8").length,4,"promotion must offer four pieces");
assert.equal(promotion.move({from:"a7",to:"a8",promotion:"q"}).promotion,"q","queen promotion must work");
const mate=new Chess();
for(const move of [{from:"f2",to:"f3"},{from:"e7",to:"e5"},{from:"g2",to:"g4"},{from:"d8",to:"h4"}])mate.move(move);
assert.equal(mate.in_checkmate(),true,"Fool's Mate must be recognized");
const stale=new Chess("7k/5Q2/6K1/8/8/8/8/8 b - - 0 1");
assert.equal(stale.in_stalemate(),true,"stalemate must be recognized");
console.log("PASS: chess legal moves, turn order, castling, promotion, checkmate and stalemate");
